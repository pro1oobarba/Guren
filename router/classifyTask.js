// Эвристика по тексту промпта — дефолт, когда вызывающий код не указал
// task явно. Не претендует на точность NLP-классификатора, просто
// избавляет от необходимости всегда передавать task руками для очевидных
// случаев ("```js ... ```" — это код, а не ролплей). Явно переданный
// task в generate() всегда имеет приоритет над этой эвристикой.
// ВАЖНО: \b (word boundary) в JS-регулярках привязан к ASCII \w и не видит
// кириллицу как "словесный" символ без /u + \p{L}. "сравни\b" тихо не
// матчится вообще — граница до и после "и" не считается границей, раз обе
// стороны не-\w. Для кириллических слов \b не используем; для английских
// (function/class/def/import) он безопасен и оставлен.
const PATTERNS = [
  // Код: код-блок, характерные конструкции, явная просьба на естественном языке.
  [
    'code',
    /```|\bfunction\b|\bclass\s+\w+|\bdef\s+\w+\(|\bimport\s+\w+|traceback|stack trace|\bexception\b|\bsyntaxerror\b|напиши (код|функци|скрипт)|исправь (этот )?код|отладь|debug/i,
  ],
  // Ролплей: обращение "ты — персонаж", явная просьба отыграть роль/сцену.
  ['roleplay', /ты\s*[—-]\s|представь,?\s*что ты|в роли |ролплей|roleplay|отыгр(ай|ывай)|опиши сцену/i],
  // Анализ: сравнение, объяснение причин, оценка, разбор.
  ['analysis', /проанализируй|сравни|объясни,?\s*почему|разбери|оцени|плюсы и минусы|разница между/i],
];

/** @param {string} prompt @returns {'code'|'roleplay'|'analysis'|'general'} */
export function classifyTask(prompt) {
  if (!prompt) return 'general';
  for (const [task, pattern] of PATTERNS) {
    if (pattern.test(prompt)) return task;
  }
  return 'general';
}
